const STRINGS = { en: EN, fr: FR };

export type StringKey = keyof typeof EN;

function format(s: string, params?: Record<string, string | number>): string {
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`));
}

export function useT() {
  const lang = useSettings((s) => s.settings.language);
  return (key: StringKey, params?: Record<string, string | number>) =>
    format(STRINGS[lang]?.[key] ?? EN[key] ?? key, params);
}

export function t(key: StringKey, params?: Record<string, string | number>): string {
  const lang = useSettings.getState().settings.language;
  return format(STRINGS[lang]?.[key] ?? EN[key] ?? key, params);
}
